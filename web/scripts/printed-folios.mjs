/*
  Reads the printed folio (the page number printed on the page) of every
  page of every corpus PDF, and writes src/lib/printed-folios.ts: for each
  document, the runs of PDF pages whose printed number differs from the PDF
  page index, as [first PDF page, last PDF page, offset], where printed =
  PDF page - offset. A page counts only when it sits in a run of at least
  three consecutive pages with the same offset, so a stray number at the end
  of a body line is never read as a folio.

  Run from web/ with poppler on PATH:
    RECOURSE_PDF_DIR=/e/Downloads/policy-qa-corpus/all node scripts/printed-folios.mjs
*/
import { execFileSync } from "node:child_process";
import { readdirSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = process.env.RECOURSE_PDF_DIR;
if (!dir) throw new Error("Set RECOURSE_PDF_DIR to the folder of corpus PDFs.");

/* The folio printed in a page's footer or header, or null. */
function folio(text) {
  const lines = text.split(/\r?\n/).map((l) => l.replace(/\s+$/, "")).filter((l) => l.trim() !== "");
  if (lines.length === 0) return null;
  const candidates = [...lines.slice(-3).reverse(), ...lines.slice(0, 2)];
  for (const line of candidates) {
    let m = line.match(/\bPage\s+(\d{1,4})\s+of\s+\d{1,4}\b/i);
    if (m) return Number(m[1]);
    m = line.match(/^\s*(?:-\s*)?(\d{1,4})(?:\s*-)?\s*$/);
    if (m) return Number(m[1]);
    /* A number set apart at the end of a footer line ("February 2026      3"). */
    m = line.match(/\S\s{2,}(\d{1,4})$/);
    if (m) return Number(m[1]);
    m = line.match(/\bPage\s+(\d{1,4})\s*$/i);
    if (m) return Number(m[1]);
  }
  return null;
}

const out = {};
const files = readdirSync(dir).filter((f) => f.toLowerCase().endsWith(".pdf")).sort();
for (const file of files) {
  const docId = file.replace(/\.pdf$/i, "");
  let text;
  try {
    text = execFileSync("pdftotext", ["-layout", "-enc", "UTF-8", path.join(dir, file), "-"], { maxBuffer: 1 << 28 }).toString("utf8");
  } catch {
    console.warn(`skip ${file}: pdftotext failed`);
    continue;
  }
  const pages = text.split("\f");
  const offsets = pages.map((p, i) => {
    const n = folio(p);
    if (n === null) return null;
    const off = i + 1 - n;
    /* A folio far from the page index is a code or a year, not a page number. */
    return off >= -10 && off <= 60 ? off : null;
  });
  const runs = [];
  let start = 0;
  while (start < offsets.length) {
    const off = offsets[start];
    let end = start;
    while (end + 1 < offsets.length && off !== null && offsets[end + 1] === off) end += 1;
    if (off !== null && off !== 0 && end - start + 1 >= 3) runs.push([start + 1, end + 1, off]);
    start = end + 1;
  }
  if (runs.length > 0) out[docId] = runs;
  console.log(docId, pages.length - 1, "pages", JSON.stringify(runs));
}

const body = `/*
  Generated by scripts/printed-folios.mjs from the corpus PDFs; do not edit.
  For each document, runs of PDF pages whose printed page number differs from
  the PDF page index: [first PDF page, last PDF page, offset], printed = PDF
  page - offset. A page outside every run prints its PDF index or no folio.
*/
export const PRINTED_FOLIO_RUNS: Record<string, [number, number, number][]> = ${JSON.stringify(out)};

/* The printed folio of a PDF page when it differs from the PDF page index, else null. */
export function printedPage(docId: string, pdfPage: number): number | null {
  const run = PRINTED_FOLIO_RUNS[docId]?.find(([a, b]) => pdfPage >= a && pdfPage <= b);
  if (!run) return null;
  const printed = pdfPage - run[2];
  return printed > 0 && printed !== pdfPage ? printed : null;
}
`;
await writeFile(path.join(root, "src/lib/printed-folios.ts"), body, "utf8");
console.log("wrote src/lib/printed-folios.ts");
