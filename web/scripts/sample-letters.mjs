/*
  Exports the sample letters behind the intake's "Try a sample letter" door (case-page-brief section 16, J1).

  Reads ../cases/cases.csv, keeps the rows with demo = yes in file order, and reads each one's
  ../cases/letters/<id>.txt. Writes src/lib/sample-letters.ts: an array of
  { id, payer, program, service, reason, text }, where program is the plain label from
  policyqa/investigate.py's PROGRAM_LABELS (read from that file, so the two cannot drift), reason is the
  first sentence of the row's denial_reason, and text is the letter file with its line endings as git
  stores them (LF), so the module is the same on every checkout. No other column of the CSV is read
  into the module.

  Fail-closed: when a letter file is missing, shorter than 200 characters or longer than 6,000 (the
  intake's limits), when a program has no label, or when the module would carry a word of the set's
  answer key, it writes nothing, names each failure and exits 1. When the module on disk is already
  current it says "nothing changed".

  Run from web/: node scripts/sample-letters.mjs
  SAMPLE_LETTERS_CASES points it at another cases folder (a copy, for testing the refusal).
*/
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.join(root, "..");
const cases = process.env.SAMPLE_LETTERS_CASES ? path.resolve(process.env.SAMPLE_LETTERS_CASES) : path.join(repo, "cases");
const OUT = "src/lib/sample-letters.ts";
const TEXT_MIN = 200;
const TEXT_MAX = 6000;
/* Words of the set's answer key; none may reach the module (J1). Matched case-insensitively. */
const FORBIDDEN = ["intended", "trap", "hinge", "inconsistent", "not_settled"];

const lf = (s) => s.replace(/\r\n?/g, "\n");

/* RFC 4180: quoted fields, doubled quotes, commas and line breaks inside quotes. */
function parseCsv(src) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < src.length; i += 1) {
    const c = src[i];
    if (quoted) {
      if (c === '"' && src[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  const [head, ...body] = rows;
  return body.filter((r) => r.length > 1 || r[0] !== "").map((r) => Object.fromEntries(head.map((h, j) => [h, r[j] ?? ""])));
}

/* PROGRAM_LABELS from policyqa/investigate.py: the block's "key": "label" lines. */
async function programLabels() {
  const py = lf(await readFile(path.join(repo, "policyqa", "investigate.py"), "utf-8"));
  const block = py.match(/^PROGRAM_LABELS = \{\n([\s\S]*?)\n\}/m);
  if (!block) throw new Error("PROGRAM_LABELS not found in policyqa/investigate.py");
  const labels = {};
  for (const m of block[1].matchAll(/^\s*"([^"]+)":\s*"([^"]+)",?\s*$/gm)) labels[m[1]] = m[2];
  return labels;
}

/* The first sentence: up to the first . ! or ? followed by a space or the end. */
function firstSentence(s) {
  const t = s.trim();
  const m = t.match(/^[\s\S]*?[.!?](?=\s|$)/);
  return m ? m[0] : t;
}

const labels = await programLabels();
const rows = parseCsv(lf(await readFile(path.join(cases, "cases.csv"), "utf-8"))).filter((r) => r.demo === "yes");

const failures = [];
const letters = [];
for (const r of rows) {
  const program = labels[r.program];
  if (!program) failures.push(`${r.id}: no label for program "${r.program}"`);
  let text = null;
  try {
    text = lf(await readFile(path.join(cases, "letters", `${r.id}.txt`), "utf-8"));
  } catch {
    failures.push(`${r.id}: cases/letters/${r.id}.txt is missing`);
  }
  if (text !== null && text.trim().length < TEXT_MIN) failures.push(`${r.id}: the letter is ${text.trim().length} characters, under ${TEXT_MIN}`);
  if (text !== null && text.trim().length > TEXT_MAX) failures.push(`${r.id}: the letter is ${text.trim().length} characters, over ${TEXT_MAX}`);
  letters.push({ id: r.id, payer: r.payer_name, program: program ?? "", service: r.service, reason: firstSentence(r.denial_reason), text: text ?? "" });
}
if (rows.length === 0) failures.push("no row in cases/cases.csv has demo = yes");

const ts = `/*
  Generated by scripts/sample-letters.mjs. Do not edit by hand: change the script and run it again.
  Source: cases/cases.csv (the rows marked demo = yes, in file order) and cases/letters/<id>.txt.
  Every letter is synthetic, written for this demo. Each entry carries the card's id, payer, program
  label, service, the first sentence of its stated denial reason, and the letter text; nothing else.
*/

export interface SampleLetter {
  id: string;
  payer: string;
  /* The plain program label (policyqa/investigate.py PROGRAM_LABELS). */
  program: string;
  service: string;
  /* The first sentence of the letter's stated denial reason. */
  reason: string;
  /* The letter as written, LF line endings. */
  text: string;
}

export const SAMPLE_LETTERS: readonly SampleLetter[] = ${JSON.stringify(letters, null, 2)};
`;

const lower = ts.toLowerCase();
for (const w of FORBIDDEN) if (lower.includes(w)) failures.push(`the module would contain "${w}"`);

if (failures.length > 0) {
  for (const f of failures) console.error(`refused: ${f}`);
  console.error(`nothing written (${failures.length} failure${failures.length === 1 ? "" : "s"})`);
  process.exit(1);
}

const file = path.join(root, OUT);
let old = null;
try {
  old = lf(await readFile(file, "utf-8"));
} catch {
  old = null;
}
if (old === ts) {
  console.log(`unchanged ${OUT} (${letters.length} letters)`);
  console.log("nothing changed");
} else {
  await writeFile(file, ts, "utf-8");
  console.log(`${old === null ? "wrote" : "rewrote"} ${OUT} (${letters.length} letters, ${Buffer.byteLength(ts, "utf-8")} bytes)`);
}
