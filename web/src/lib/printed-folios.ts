/*
  Generated by scripts/printed-folios.mjs from the corpus PDFs; do not edit.
  For each document, runs of PDF pages whose printed page number differs from
  the PDF page index: [first PDF page, last PDF page, offset], printed = PDF
  page - offset. A page outside every run prints its PDF index or no folio.
*/
export const PRINTED_FOLIO_RUNS: Record<string, [number, number, number][]> = {"fl-01":[[2,12,1]],"fl-02":[[4,26,1],[28,78,1]],"fl-03":[[3,9,2]],"fl-04":[[3,8,2]],"fl-05":[[3,9,2]],"fl-06":[[3,11,1]],"fl-07":[[3,16,2]],"fl-08":[[3,8,2]],"fl-09":[[3,8,2]],"fl-10":[[3,8,2]],"fl-11":[[3,11,2],[12,17,11]],"fl-12":[[3,10,2]],"fl-13":[[3,8,2]],"fl-14":[[3,8,2]],"fl-15":[[3,8,2]],"fl-16":[[3,22,2]],"fl-17":[[3,10,2]],"fl-30":[[5,111,4]]};

/* The printed folio of a PDF page when it differs from the PDF page index, else null. */
export function printedPage(docId: string, pdfPage: number): number | null {
  const run = PRINTED_FOLIO_RUNS[docId]?.find(([a, b]) => pdfPage >= a && pdfPage <= b);
  if (!run) return null;
  const printed = pdfPage - run[2];
  return printed > 0 && printed !== pdfPage ? printed : null;
}
